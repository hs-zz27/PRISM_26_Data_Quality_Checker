"""Render the future endpoint guide from the same inputs as OpenAPI."""

import json

from .common import BASE_PATH, JsonObject


def _json_block(value: object) -> list[str]:
    return ["```json", json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False), "```", ""]


def render_planned_endpoints(contract: JsonObject) -> str:
    """Include every planned operation, its examples and referenced schemas."""
    operations = [
        (path, method, operation)
        for path, methods in contract["paths"].items()
        for method, operation in methods.items()
        if operation["x-implementation-status"] == "planned"
    ]
    lines = [
        "# Planned endpoint reference", "",
        "Generated from the contract inputs. Do not edit this file directly.", "",
        f"All {len(operations)} operations below are **planned and unavailable on the running backend**. "
        "They are frontend implementation targets and mock contracts, not runtime guarantees. "
        "Coordinate changes as each backend feature is implemented.", "",
        "Use [FRONTEND_WORKFLOW.md](FRONTEND_WORKFLOW.md) for screen flows, "
        "[openapi.json](openapi.json) for machine-readable schemas and "
        "[examples.json](examples.json) for fixtures. "
        "[implemented-openapi.json](implemented-openapi.json) contains only callable operations.", "",
        "## Shared conventions", "",
        "- Paths include `/api/v1`; apply the backend origin or development proxy once.",
        "- Required fields, nullability and defaults are in the schema appendix. Null does not imply optional.",
        "- Multipart binary fields are File/Blob values in FormData. Marker strings below are placeholders; "
        "do not send them as JSON or base64. Let the browser set multipart boundaries.",
        "- HTTP 202 accepts work. Poll the returned job or the wrapper's job field. "
        "Failed jobs are read with HTTP 200 and job.error. Follow result.href only when present.",
        "- List defaults: limit=20, offset=0; request limit is 1–100. "
        "Omit optional query filters to disable them; follow next_offset until null.",
        "- Error codes below are proposed contracts. Immediate HTTP errors use ErrorResponse; "
        "post-acceptance failures use Job.error. Keep a safe fallback for unknown codes.",
        "- Reviewer IDs are attribution in the local prototype, not authentication credentials.", "",
        "Common error envelope:", "",
    ]
    lines.extend(_json_block({"error": {
        "code": "VALIDATION_ERROR", "message": "One or more request fields are invalid.",
        "details": [{"field": "body.field_name", "message": "A required field is missing."}],
        "request_id": "request_demo",
    }}))
    lines.extend(["## Operation index", ""])
    for path, method, operation in operations:
        identifier = operation["operationId"]
        lines.append(f"- [`{method.upper()} {BASE_PATH}{path}`](#{identifier.lower()}) — {operation['summary']}.")
    lines.append("")
    referenced: set[str] = set()

    def collect(value: object) -> None:
        if isinstance(value, dict):
            reference = value.get("$ref", "")
            if reference.startswith("#/components/schemas/"):
                referenced.add(reference.rsplit("/", 1)[-1])
            for child in value.values():
                collect(child)
        elif isinstance(value, list):
            for child in value:
                collect(child)

    for path, method, operation in operations:
        collect(operation)
        lines.extend([f"## {operation['operationId']}", "",
                      f"`{method.upper()} {BASE_PATH}{path}` — {operation['summary']}", "",
                      operation["description"], "", "**Parameters**", ""])
        parameters = operation.get("parameters", [])
        if not parameters:
            lines.extend(["None.", ""])
        for parameter in parameters:
            required = "required" if parameter["required"] else "optional"
            schema = json.dumps(parameter["schema"], ensure_ascii=False, sort_keys=True)
            lines.extend([f"- `{parameter['name']}` ({parameter['in']}, {required}): `{schema}`. "
                          + parameter.get("description", ""),
                          f"  Example: `{json.dumps(parameter['example'], ensure_ascii=False)}`.", ""])
        lines.extend(["**Request**", ""])
        body = operation.get("requestBody")
        if body is None:
            lines.extend(["No request body.", ""])
        else:
            for media_type, media in body["content"].items():
                model = media["schema"]["$ref"].rsplit("/", 1)[-1]
                lines.extend([f"Required `{media_type}` body; schema `{model}` (see appendix).", ""])
                if media_type == "multipart/form-data":
                    lines.extend(["FormData fields; binary marker strings mean actual File/Blob parts:", ""])
                lines.extend(_json_block(media["example"]))
        lines.extend(["**Success response**", ""])
        for status, response in operation["responses"].items():
            if not status.startswith("2"):
                continue
            for media_type, media in response.get("content", {}).items():
                model = media["schema"].get("$ref", "binary").rsplit("/", 1)[-1]
                lines.extend([f"HTTP {status}, `{media_type}`, schema `{model}`.", ""])
                if "example" in media:
                    lines.extend(_json_block(media["example"]))
                else:
                    lines.extend(["Binary body. Read a successful download as bytes/Blob; errors remain JSON.", ""])
        lines.extend(["**HTTP errors**", ""])
        for status, response in operation["responses"].items():
            if status.startswith("2"):
                continue
            media = response["content"]["application/json"]
            examples = [media["example"]] if "example" in media else [
                entry["value"] for entry in media.get("examples", {}).values()
            ]
            for example in examples:
                error = example["error"]
                lines.append(f"- HTTP {status}, `{error['code']}`: {error['message']}")
        lines.append("")

    schemas = contract["components"]["schemas"]
    expanded: set[str] = set()
    while referenced - expanded:
        name = sorted(referenced - expanded)[0]
        collect(schemas[name])
        expanded.add(name)
    lines.extend(["## Referenced schemas", "",
                  "Exact definitions from the combined OpenAPI contract. Local references resolve "
                  "to other definitions below; use openapi.json for machine tooling.", ""])
    for name in sorted(expanded):
        lines.extend([f"### {name}", ""])
        lines.extend(_json_block(schemas[name]))
    return "\n".join(lines)
